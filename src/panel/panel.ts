import { builtInStatus, downloadBuiltIn, type BuiltInStatus } from "../shared/builtin-ai";
import { getEnginePref, setEnginePref, type EnginePref } from "../shared/engine-pref";

const STATUS_TEXT: Record<BuiltInStatus, string> = {
  available: "Ready. Answers are generated by Chrome's own on-device model.",
  downloadable: "Not downloaded yet. Until then Explain This uses WebLLM.",
  downloading: "Chrome is downloading it. Check back in a few minutes.",
  unavailable: "This device can't run it, so Explain This uses WebLLM.",
  unsupported: "This version of Chrome doesn't offer it, so Explain This uses WebLLM."
};

const statusEl = document.getElementById("status") as HTMLParagraphElement;
const downloadBtn = document.getElementById("download") as HTMLButtonElement;
const track = document.getElementById("progress-track") as HTMLDivElement;
const bar = document.getElementById("progress-bar") as HTMLDivElement;

async function refresh() {
  const status = await builtInStatus();
  statusEl.textContent = STATUS_TEXT[status];
  downloadBtn.hidden = status !== "downloadable";
}

downloadBtn.addEventListener("click", async () => {
  downloadBtn.disabled = true;
  track.hidden = false;
  try {
    await downloadBuiltIn((fraction) => {
      bar.style.width = `${Math.round(fraction * 100)}%`;
    });
  } catch (err) {
    console.warn("Explain This: built-in model download failed", err);
    statusEl.textContent = "The download didn't start. Try again in a moment.";
  } finally {
    downloadBtn.disabled = false;
    track.hidden = true;
    bar.style.width = "0";
    await refresh();
  }
});

const current = getEnginePref();
for (const radio of document.querySelectorAll<HTMLInputElement>('input[name="engine"]')) {
  radio.checked = radio.value === current;
  radio.addEventListener("change", () => setEnginePref(radio.value as EnginePref));
}

refresh();
